function cals = catalog(luminose)
% lhf.cal.catalog  The rig's calibrations: what each needs, does and can be set to.
%
%   cals = lhf.cal.catalog(luminose)
%
%   One struct per calibration, in the order the Calibration window lists them:
%       id        'cameraDmd', 'stageCamera', 'zFocus' or 'power'
%       title     its name in the window
%       about     what it measures and what uses the result
%       before    what to set up at the rig first
%       devices   the shared devices it uses (lhf.device names)
%       files     the file pattern it saves in luminoseData/calibration
%       settings  struct array: key, label, unit, value (the default, from
%                 luminose_config.yaml where the config has one), kind
%                 ('number', 'vector', 'logical' or 'choice'), choices, tip
%   The settings are what the old scripts hard-coded; lhf.cal.run takes them as
%   a struct (lhf.cal.settings turns this list into one).
%
% See also lhf.cal.run, lhf.cal.settings, gui/CalibrationApp

    exposure = luminose.camera.exposureTime_ms;
    average = luminose.camera.nAverageFrames;
    camera = [ ...
        setting('exposureMs', 'Exposure', 'ms', exposure, 'number', ...
            'Camera exposure while calibrating (put back afterwards)'), ...
        setting('averageFrames', 'Average', 'frames', average, 'number', ...
            'Frames averaged per capture (put back afterwards)')];

    cals = struct('id', {}, 'title', {}, 'about', {}, 'before', {}, 'devices', {}, ...
        'files', {}, 'settings', {});

    cals(end + 1) = struct('id', 'cameraDmd', 'title', 'Camera - DMD', ...
        'about', ['Projects one spot at a time on a grid across the DMD, finds each on the camera ' ...
            'and fits an affine map from DMD pixels to full-sensor camera pixels. The Pattern ' ...
            'Designer uses the newest one to place spots on the camera image.'], ...
        'before', ['A flat fluorescent or reflective target at the sample plane, in focus; the ' ...
            'laser on at a low power (the DMD gates it). Set the exposure so a spot is bright ' ...
            'but not saturated.'], ...
        'devices', {{'camera', 'dmd'}}, 'files', 'camera_dmd_*.mat', ...
        'settings', [ ...
            setting('gridX', 'Spots across', '', 6, 'number', 'Columns of the spot grid'), ...
            setting('gridY', 'Spots down', '', 5, 'number', 'Rows of the spot grid'), ...
            setting('marginPx', 'Margin', 'DMD px', 80, 'number', ...
                'DMD pixels kept clear at each edge of the field'), ...
            setting('spotRadiusPx', 'Spot half-width', 'DMD px', 6, 'number', ...
                'Each spot is a square of 2 r + 1 mirrors'), ...
            setting('settleS', 'Settle', 's', 0.3, 'number', 'Wait after each new DMD frame'), ...
            setting('maxRmsPx', 'Warn above rms', 'camera px', 2, 'number', ...
                'A fit worse than this is flagged (check focus and exposure)'), ...
            setting('outlierPx', 'Drop beyond', 'camera px', 5, 'number', ...
                'A spot further than this from the fitted map is dropped (hot pixel, dust)'), ...
            camera]);

    cals(end + 1) = struct('id', 'stageCamera', 'title', 'Stage - camera', ...
        'about', ['Moves X and Y by +/- the step, registers each image on the first and fits how ' ...
            'a stage move shifts the camera image (camera px per um, rotation, directions). ' ...
            'Align to reference in the Pattern Designer uses the newest one.'], ...
        'before', ['A sample with texture (tissue, or a slide with features) in focus and lit. ' ...
            'zaber.axes set in luminose_config.yaml. X and Y return to where they started.'], ...
        'devices', {{'camera', 'stage'}}, 'files', 'stage_camera_*.mat', ...
        'settings', [ ...
            setting('stepUm', 'Step', 'um', 100, 'number', 'How far X and Y move each way'), ...
            setting('settleS', 'Settle', 's', 0.2, 'number', 'Wait after each move'), ...
            setting('downsample', 'Downsample', 'x', 2, 'number', ...
                'Registration works on frames shrunk by this factor'), ...
            camera]);

    zStep = 50;
    try zStep = luminose.zaber.zStep_um; catch, end
    focus = 19000;
    try focus = luminose.zaber.focus_um; catch, end
    cals(end + 1) = struct('id', 'zFocus', 'title', 'Z focus', ...
        'about', ['Shows one small spot on the DMD, steps Z across a range and sums the camera ' ...
            'frame at each plane; the brightest plane is the focus of the DMD on the sample.'], ...
        'before', ['A flat target at the sample plane and the laser on at a low power. Z moves ' ...
            'only within the scan, cut to Z''s limits (the Stage panel''s), then returns to where ' ...
            'it started.'], ...
        'devices', {{'camera', 'dmd', 'stage'}}, 'files', 'zprofile_*.mat', ...
        'settings', [ ...
            setting('centreUm', 'Centre', 'um', focus, 'number', ...
                'Middle of the scan (zaber.focus_um, the nominal focus)'), ...
            setting('rangeUm', 'Range +/-', 'um', 5000, 'number', 'The scan covers centre +/- this'), ...
            setting('stepUm', 'Step', 'um', zStep, 'number', 'Z step between planes (zaber.zStep_um)'), ...
            setting('spotRadiusPx', 'Spot half-width', 'DMD px', 0, 'number', ...
                '0: a single mirror at the DMD centre'), ...
            setting('returnToStart', 'Return to start', '', true, 'logical', ...
                'Move Z back to where it started when done'), ...
            camera]);

    setpoints = [];
    try
        table = readtable(powerCsv(luminose));
        setpoints = table.power_setting_mW(:)';
    catch
    end
    cals(end + 1) = struct('id', 'power', 'title', 'Laser power', ...
        'about', ['Steps the laser through its setpoints with the DMD all on, reading the power ' ...
            'meter at the sample (if chosen) and the camera intensity over the lit field. ' ...
            'Saved, it rewrites dmd/power_calibration.csv, which converts irradiances to ' ...
            'setpoints for every session.'], ...
        'before', ['The power meter sensor at the sample plane (Meter PM100D), or the meter ' ...
            'values already in the CSV for these setpoints (Meter none). Close Thorlabs Optical ' ...
            'Power Monitor. Emission is turned off when it ends, however it ends.'], ...
        'devices', {{'camera', 'dmd', 'laser'}}, 'files', 'power_*.mat', ...
        'settings', [ ...
            setting('setpointsmW', 'Setpoints', 'mW', setpoints, 'vector', ...
                'Laser setpoints in order (default: the CSV''s)'), ...
            setting('settleS', 'Settle', 's', 0.3, 'number', 'Wait after each new setpoint'), ...
            setting('meter', 'Meter', '', 'none', 'choice', ...
                'PM100D: read the power at the sample at each setpoint; none: keep the CSV''s', ...
                {'none', 'PM100D'}), ...
            setting('meterSamples', 'Meter readings', '', 20, 'number', 'Readings averaged per setpoint'), ...
            setting('meterWavelengthNm', 'Meter wavelength', 'nm', 0, 'number', ...
                'Sets the meter''s correction; 0 leaves it as it is'), ...
            setting('useCamera', 'Camera intensity', '', true, 'logical', ...
                'Also record the mean camera counts over the lit field'), ...
            camera]);
end


function s = setting(key, label, unit, value, kind, tip, choices)
    if nargin < 7, choices = {}; end
    s = struct('key', key, 'label', label, 'unit', unit, 'value', value, 'kind', kind, ...
        'choices', {choices}, 'tip', tip);
end

function file = powerCsv(luminose)
    file = fullfile(char(luminose.f.luminose_hf), 'dmd', 'power_calibration.csv');
end
